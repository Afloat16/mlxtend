"""Floating targets should work without a caller-side precision conversion."""

import numpy as np
import pytest

from mlxtend.regressor import LinearRegression


@pytest.mark.parametrize("dtype", [np.float16, np.float32, np.float64])
@pytest.mark.parametrize("method", ["direct", "qr", "svd", "sgd"])
def test_floating_targets_fit_all_linear_regression_solvers(dtype, method):
    x = np.array([[-1, 0], [0, 1], [1, 0], [0, -1]], dtype=np.float32)
    y = np.array([-1.5, -2.5, 2.5, 3.5], dtype=dtype)
    original_x, original_y = x.copy(), y.copy()
    kwargs = {"minibatches": 1, "eta": 0.1, "epochs": 200} if method == "sgd" else {}
    model = LinearRegression(method=method, random_seed=0, **kwargs)

    assert model.fit(x, y) is model

    # These exact targets are generated by y = 2*x0 - 3*x1 + 0.5.
    np.testing.assert_allclose(model.w_.ravel(), [2, -3], atol=1e-10, rtol=0)
    np.testing.assert_allclose(model.b_, [0.5], atol=1e-10, rtol=0)
    np.testing.assert_allclose(
        model.predict(x), y.astype(np.float64), atol=1e-10, rtol=0
    )
    np.testing.assert_array_equal(x, original_x)
    np.testing.assert_array_equal(y, original_y)
    assert y.dtype == dtype


@pytest.mark.parametrize("dtype", [np.int32, np.int64, np.complex64, np.bool_])
def test_non_floating_targets_keep_the_existing_error(dtype):
    x = np.array([[0.0], [1.0], [2.0]])
    y = np.array([0, 1, 1], dtype=dtype)
    with pytest.raises(AttributeError, match="y must be a float array"):
        LinearRegression().fit(x, y)
